#pragma once

// VkWorld: a Vulkan mirror of GpuSolver::Impl (solver_impl), owning
// every device buffer the AVBD step touches and orchestrating src/world's
// already-tested per-phase launchers (VkBroadphase, VkNarrowphase, VkConstraints,
// SolverPipelines, IntegratePipelines, SleepPipelines/WakePipelines/MutatePipelines)
// into one step() with a fixed phase order.
//
// Build seam: VkWorld::build() takes a SceneDesc (src/scene/scene_desc.h) -- the
// finalized import record a SceneBuilder produces -- and never reaches into any other solver.
// From here on VkWorld runs entirely against its own Vulkan Device and Buffers.
//
// Scope (disclosed, matching the rest of src/world's phase comments):
//  - No drag/pick reservation: jointsTotal == the authored joint count from the
//    mirror. Drag is a separate feature (vk_interact.h) layered on top of a running
//    VkWorld, out of scope for this step/sleep/capacity/reset gate.
//  - External mutations (setBodyData and its single-body conveniences, wakeRegion)
//    mirror the mutation path: writes queue on the host, apply at the top of the next step()
//    in submission order, and seed an explicit wake flood (launchWakeFlood) that runs
//    after the implicit detect and before the joint-island flood. getBodyData gathers
//    synchronously. The implicit velocity-gated wake path (launchWakeDetect/
//    launchWakeIslandSeed/launchWakeApply) is wired every step, and the joint-island
//    wake flood (launchWakeIslandSeed -> launchWakeFloodJoints rounds ->
//    launchWakeSeedMerge) reaches VkWorld::step()'s fixed point exactly. Since M4 both floods
//    are recorded to a bound in the step's one phase-4 submission, with the merge gated
//    on the last round having changed nothing; see step() for why that is exact.
//  - Growth: reserve()/grow() mirror the capacity code's cappedGrow() policy exactly (same
//    single-shot need+need/4+slack formula and kMaxPairCapacity ceiling, duplicated
//    locally since it is a private static in VkWorld::step()). VkNarrowphase::grow()
//    preserves the persistent contact cache (feature keys, lambda, penalty, stick)
//    across a mid-run overflow via Buffer::resizePreserve(), mirroring the capacity code's
//    reserveKeep().

